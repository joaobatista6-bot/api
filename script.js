function buscarCachorro(event) {

    if (event) {
        event.preventDefault();
    }

    const campoRaca = document.getElementById("raca");

    if (!campoRaca) {
        return;
    }

    const raca = campoRaca.value.trim().toLowerCase();

    let url;

    if (raca === "") {
        url = "https://dog.ceo/api/breeds/image/random";
    } else {
        url = `https://dog.ceo/api/breed/${raca}/images/random`;
    }

    const resultado = document.getElementById("resultado");
    const mensagem = document.getElementById("mensagem");

    resultado.innerHTML = `
        <div class="carregando">
            Procurando...
        </div>
    `;

    mensagem.textContent = "";

    fetch(url)

        .then(resposta => {

            if (!resposta.ok) {
                throw new Error("Erro HTTP");
            }

            return resposta.json();

        })

        .then(dados => {

            if (dados.status !== "success") {

                resultado.innerHTML = "";

                mensagem.textContent =
                    "Raça não encontrada. Verifique o nome e tente novamente.";

                return;
            }


            const info = informacoes[raca];

            const nomeExibicao =
                raca === ""
                    ? "Cachorro aleatório"
                    : (info?.nome || formatarNome(raca));


            let html = `

                <div class="cachorro-card">

                    <h2>${nomeExibicao}</h2>

                    <img
                        src="${dados.message}"
                        alt="${nomeExibicao}"
                        class="imagem-cachorro"
                    >

            `;


            if (info) {

                html += `

                    <section class="informacoes">

                        <h3>Informações da raça</h3>

                        <div class="dados-raca">

                            <div class="dado">
                                <span>Altura</span>
                                <strong>${info.altura}</strong>
                            </div>

                            <div class="dado">
                                <span>Peso</span>
                                <strong>${info.peso}</strong>
                            </div>

                            <div class="dado">
                                <span>Expectativa de vida</span>
                                <strong>${info.expectativa}</strong>
                            </div>

                            <div class="dado">
                                <span>Origem</span>
                                <strong>${info.origem}</strong>
                            </div>

                        </div>

                        <div class="personalidade">

                            <span>Personalidade</span>

                            <p>${info.personalidade}</p>

                        </div>

                    </section>


                    <section class="caracteristicas">

                        <h3>Características</h3>

                        <ul>

                `;


                info.caracteristicas.forEach(caracteristica => {

                    html += `
                        <li>${caracteristica}</li>
                    `;

                });


                html += `

                        </ul>

                    </section>

                `;

            } else {

                html += `

                    <section class="sem-informacoes">

                        <p>
                            Não temos informações detalhadas cadastradas
                            para esta raça.
                        </p>

                    </section>

                `;

            }


            html += `

                </div>

            `;


            resultado.innerHTML = html;

        })

        .catch(erro => {

            console.error(erro);

            resultado.innerHTML = "";

            mensagem.textContent =
                "Erro ao acessar a API. Verifique sua conexão com a internet.";

        });

}


function formatarNome(nome) {

    return nome
        .replace(/_/g, " ")
        .replace(/\b\w/g, letra => letra.toUpperCase());

}


document.addEventListener("DOMContentLoaded", () => {

    const campoRaca = document.getElementById("raca");

    if (campoRaca) {

        campoRaca.addEventListener("keydown", event => {

            if (event.key === "Enter") {
                buscarCachorro(event);
            }

        });

    }

});